/**
 * Official report drafts (blueprint v4 §26 "Official reports"; checklist §6).
 *
 * Deterministic, version-controlled templates rendered to Markdown, a
 * standalone script-free HTML file, a machine-readable JSON manifest and a
 * formula-safe CSV of affected URLs. Allegations are framed as observations;
 * a deadline appears only when a lawful one is recorded; the signature block
 * is left blank for the actual signatory. Hindi headings are offered for
 * bilingual drafts, but body text needs approved human translation.
 */
import { csvCell } from '../export/exporter.js';
import { canonicalJson } from '../evidence/canonical.js';
import { formatIst } from '../evidence/time.js';
import { LEGAL_ROUTES, SECTION_69A_GROUNDS, type RouteId } from './legalRoutes.js';

export const REPORT_TEMPLATE_VERSION = 'notice-templates-2026.10.1';

export interface ReportTarget {
  url: string;
  registrable_domain: string;
  legal_ground: string | null;
  evidence: { attempt_id: string; observed_at_utc: string; outcome: string | null; final_url: string | null; manifest_sha256: string | null; screenshot_sha256: string | null; vantage: string | null }[];
  identifiers: { field_type: string; value: string; method: string }[];
}

export interface ReportInput {
  notice: {
    id: string; route: RouteId; reference_no: string | null; language: 'en' | 'hi' | 'en_hi'; recipient: { name?: string; kind?: string; contact?: string; jurisdiction?: string };
    legal_basis: string | null; authority_ref: string | null; issuing_authority: string | null; signatory_name: string | null; signatory_designation: string | null;
    jurisdiction: string | null; facts_summary: string | null; requested_action: string | null; lawful_deadline: string | null; route_fields: Record<string, unknown>;
    approved_by: string | null; approved_at: string | null; created_by: string;
  };
  caseRef: string;
  targets: ReportTarget[];
  generatedAt: string;
  evidencePackage: { id: string; index_sha256: string } | null;
  maskIdentifiers: boolean;
}

const HI: Record<string, string> = {
  reference: 'संदर्भ संख्या', date: 'दिनांक', to: 'प्रति', subject: 'विषय', facts: 'तथ्य (अवलोकन)', urls: 'संबंधित यूआरएल',
  basis: 'कानूनी/नीतिगत आधार', request: 'अनुरोधित कार्रवाई', deadline: 'समय-सीमा', enclosures: 'संलग्नक', signatory: 'हस्ताक्षरकर्ता',
};

/** Mask the middle of a sensitive identifier for recipients not entitled to the full value. */
export function maskValue(v: string): string {
  if (v.length <= 6) return '•'.repeat(v.length);
  const at = v.indexOf('@');
  if (at > 0) return `${v.slice(0, Math.min(2, at))}•••${v.slice(at)}`;
  return `${v.slice(0, 3)}${'•'.repeat(Math.max(3, v.length - 6))}${v.slice(-3)}`;
}

function heading(key: keyof typeof HI, en: string, lang: ReportInput['notice']['language']): string {
  return lang === 'en' ? en : lang === 'hi' ? `${HI[key]} (${en})` : `${en} / ${HI[key]}`;
}

export interface RenderedReport {
  markdown: string;
  html: string;
  json: Record<string, unknown>;
  csv: string;
  snapshot: Record<string, unknown>;
}

/** The exact content an approver signs off; its hash is stored at approval and checked at generation. */
export function approvalSnapshot(i: Pick<ReportInput, 'notice' | 'targets'>): Record<string, unknown> {
  const n = i.notice;
  return {
    template_version: REPORT_TEMPLATE_VERSION, route: n.route, reference_no: n.reference_no, language: n.language, recipient: n.recipient,
    legal_basis: n.legal_basis, authority_ref: n.authority_ref, issuing_authority: n.issuing_authority, signatory_name: n.signatory_name,
    signatory_designation: n.signatory_designation, jurisdiction: n.jurisdiction, facts_summary: n.facts_summary, requested_action: n.requested_action,
    lawful_deadline: n.lawful_deadline, route_fields: n.route_fields,
    targets: i.targets.map((t) => ({ url: t.url, legal_ground: t.legal_ground, evidence: t.evidence.map((e) => ({ attempt_id: e.attempt_id, manifest_sha256: e.manifest_sha256 })) })),
  };
}

export function renderReport(i: ReportInput): RenderedReport {
  const n = i.notice;
  const route = LEGAL_ROUTES[n.route];
  const lang = n.language;
  const date = formatIst(i.generatedAt);
  const mask = (v: string) => (i.maskIdentifiers ? maskValue(v) : v);
  const subject = `${route.title}: ${i.targets.length} URL(s) — case ${i.caseRef}`;
  const ground69a = n.route === 'it_act_69a_blocking' ? SECTION_69A_GROUNDS[n.route_fields.ground_69a as keyof typeof SECTION_69A_GROUNDS] : null;

  const md: string[] = [];
  md.push(`# DRAFT — ${route.title}`, '');
  md.push(`> Draft generated by the collector from an approved snapshot. It is not issued until an authorised officer signs and dispatches it through an approved channel. ${route.guardrail}`, '');
  md.push(`**${heading('reference', 'Reference No.', lang)}:** ${n.reference_no ?? '(to be assigned)'}  `);
  md.push(`**${heading('date', 'Date', lang)}:** ${date}  `);
  md.push(`**From:** ${n.issuing_authority ?? '(issuing authority)'}  `);
  md.push(`**${heading('to', 'To', lang)}:** ${n.recipient.name ?? '(recipient)'}${n.recipient.contact ? ` <${n.recipient.contact}>` : ''}${n.recipient.jurisdiction ? ` — ${n.recipient.jurisdiction}` : ''}  `);
  md.push(`**${heading('subject', 'Subject', lang)}:** ${subject}`, '');
  md.push(`## ${heading('facts', 'Facts (observations)', lang)}`, '', n.facts_summary ?? '', '');
  md.push(`## ${heading('urls', 'Affected URLs and evidence', lang)}`, '');
  md.push('| # | URL | Observed (IST) | Outcome | Evidence (attempt) | Manifest SHA-256 |', '|---|---|---|---|---|---|');
  i.targets.forEach((t, idx) => {
    const e = t.evidence[0];
    md.push(`| ${idx + 1} | ${t.url.replace(/\|/g, '%7C')} | ${e ? formatIst(e.observed_at_utc) : '-'} | ${e?.outcome ?? '-'} | ${e?.attempt_id ?? '-'} | ${e?.manifest_sha256 ?? '-'} |`);
  });
  md.push('');
  for (const t of i.targets) {
    const leads = t.identifiers.slice(0, 15).map((x) => `${x.field_type}: ${mask(x.value)} (${x.method})`);
    if (leads.length || t.legal_ground) md.push(`**${t.url}** — ${t.legal_ground ? `ground: ${t.legal_ground}. ` : ''}${leads.length ? `Observed identifiers: ${leads.join('; ')}.` : ''}`, '');
  }
  md.push(`## ${heading('basis', 'Legal / policy basis', lang)}`, '', n.legal_basis ?? '', ...(ground69a ? ['', `Ground under s.69A(1): ${ground69a}.`] : []),
    ...(n.authority_ref ? ['', `Authority/authorisation reference: ${n.authority_ref}.`] : []), ...(n.jurisdiction ? ['', `Jurisdiction: ${n.jurisdiction}.`] : []), '');
  md.push(`## ${heading('request', 'Requested action', lang)}`, '', n.requested_action ?? '', '');
  if (n.lawful_deadline) md.push(`## ${heading('deadline', 'Response period', lang)}`, '', `${n.lawful_deadline} (applies only from documented receipt of this communication).`, '');
  if (route.timing_note) md.push(`> ${route.timing_note}`, '');
  md.push(`## ${heading('enclosures', 'Enclosures', lang)}`, '');
  md.push(i.evidencePackage ? `- Evidence package ${i.evidencePackage.id}; package-index SHA-256 ${i.evidencePackage.index_sha256}.` : '- Evidence package: to be attached.');
  md.push('- Each listed manifest SHA-256 identifies the immutable capture record of the observation cited above.', '');
  md.push(`## ${heading('signatory', 'Signatory', lang)}`, '', `${n.signatory_name ?? '(name)'}, ${n.signatory_designation ?? '(designation)'}`, '', 'Signature: ______________________   Date/Time (IST): ______________', '');
  md.push('---', `Screenshots are observations of one browser session at the stated time from the stated vantage. They do not by themselves establish domain ownership, what other visitors saw, or legal admissibility. Template ${REPORT_TEMPLATE_VERSION}.`);
  if (lang !== 'en') md.push('', 'Hindi headings only: the body text requires an approved human translation before use.');
  const markdown = `${md.join('\n')}\n`;

  const json = {
    format: 'cyber-web-collector/notice-draft@1', template_version: REPORT_TEMPLATE_VERSION, notice_id: n.id, route: n.route, route_title: route.title,
    reference_no: n.reference_no, generated_at_utc: i.generatedAt, generated_at_ist: date, case_ref: i.caseRef, recipient: n.recipient,
    issuing_authority: n.issuing_authority, legal_basis: n.legal_basis, ground_69a: ground69a, authority_ref: n.authority_ref, jurisdiction: n.jurisdiction,
    facts_summary: n.facts_summary, requested_action: n.requested_action, lawful_deadline: n.lawful_deadline, route_fields: n.route_fields,
    targets: i.targets.map((t) => ({ ...t, identifiers: t.identifiers.map((x) => ({ ...x, value: mask(x.value) })) })),
    approvals: { author: n.created_by, approver: n.approved_by, approved_at: n.approved_at },
    evidence_package: i.evidencePackage, status: 'DRAFT_NOT_ISSUED', identifiers_masked: i.maskIdentifiers,
  };

  const csvLines = [['url', 'registrable_domain', 'legal_ground', 'attempt_id', 'observed_at_ist', 'outcome', 'final_url', 'manifest_sha256', 'screenshot_sha256'].join(',')];
  for (const t of i.targets) {
    for (const e of t.evidence.length ? t.evidence : [null]) {
      csvLines.push([t.url, t.registrable_domain, t.legal_ground, e?.attempt_id, e ? formatIst(e.observed_at_utc) : '', e?.outcome, e?.final_url, e?.manifest_sha256, e?.screenshot_sha256].map(csvCell).join(','));
    }
  }

  return { markdown, html: markdownToSafeHtml(markdown, subject), json, csv: `${csvLines.join('\n')}\n`, snapshot: approvalSnapshot(i) };
}

export function snapshotText(snapshot: Record<string, unknown>): string {
  return canonicalJson(snapshot);
}

const escapeHtml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');

/** Minimal Markdown→HTML for the fixed template above. Everything is escaped; no links, scripts or remote assets. */
export function markdownToSafeHtml(md: string, title: string): string {
  const out: string[] = [];
  let inTable = false;
  let para: string[] = [];
  const inline = (s: string) => escapeHtml(s).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
  const flush = () => {
    if (para.length) out.push(`<p>${para.map(inline).join('<br>')}</p>`);
    para = [];
  };
  for (const raw of md.split('\n')) {
    const line = raw.replace(/ {2}$/, '');
    if (line.startsWith('|')) {
      flush();
      const cells = line.slice(1, -1).split('|').map((c) => c.trim());
      if (cells.every((c) => /^-+$/.test(c))) continue;
      if (!inTable) {
        out.push('<table><thead><tr>', ...cells.map((c) => `<th>${inline(c)}</th>`), '</tr></thead><tbody>');
        inTable = true;
      } else out.push('<tr>', ...cells.map((c) => `<td>${inline(c)}</td>`), '</tr>');
      continue;
    }
    if (inTable) {
      out.push('</tbody></table>');
      inTable = false;
    }
    if (line.startsWith('# ')) { flush(); out.push(`<h1>${inline(line.slice(2))}</h1>`); }
    else if (line.startsWith('## ')) { flush(); out.push(`<h2>${inline(line.slice(3))}</h2>`); }
    else if (line.startsWith('> ')) { flush(); out.push(`<blockquote>${inline(line.slice(2))}</blockquote>`); }
    else if (line.startsWith('- ')) { flush(); out.push(`<ul><li>${inline(line.slice(2))}</li></ul>`); }
    else if (line === '---') { flush(); out.push('<hr>'); }
    else if (line.trim() === '') flush();
    else para.push(line);
  }
  flush();
  if (inTable) out.push('</tbody></table>');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'">
<title>${escapeHtml(title)}</title>
<style>body{font:15px/1.5 "Noto Sans","Noto Sans Devanagari",Arial,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem;color:#111}
table{border-collapse:collapse;width:100%;font-size:13px}th,td{border:1px solid #999;padding:4px 6px;text-align:left;word-break:break-all}
blockquote{border-left:4px solid #b45309;margin:1rem 0;padding:.5rem 1rem;background:#fff7ed}h1{font-size:1.4rem}h2{font-size:1.1rem;margin-top:1.6rem}</style>
</head><body>
${out.join('\n')}
</body></html>
`;
}
